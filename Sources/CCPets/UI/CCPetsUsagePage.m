- (void)bind:(NSControl *)control to:(void (^)(id sender))block {
    CCPetsUsageHandler *handler = [CCPetsUsageHandler new];
    handler.block = block;
    [self.handlers addObject:handler];
    control.target = handler;
    control.action = @selector(invoke:);
}

- (NSSegmentedControl *)segmentedWithLabels:(NSArray<NSString *> *)labels selected:(NSInteger)selected {
    NSSegmentedControl *control = [NSSegmentedControl segmentedControlWithLabels:labels
        trackingMode:NSSegmentSwitchTrackingSelectOne target:nil action:nil];
    control.controlSize = NSControlSizeSmall;
    control.font = [NSFont systemFontOfSize:NSFont.smallSystemFontSize];
    control.selectedSegment = selected;
    CCPetsApplyAccent(control);
    return control;
}

- (void)loadView {
    self.handlers = [NSMutableArray array];
    self.form = [[CCPetsFormBuilder alloc] initWithTitle:L(@"Usage") subtitle:@""];
    __weak typeof(self) weakSelf = self;

    self.sourceControl = [self segmentedWithLabels:@[L(@"All")] selected:0];
    [self bind:self.sourceControl to:^(id sender) {
        weakSelf.selectedKey = nil;
        [weakSelf render];
    }];
    self.sourcePopup = [[NSPopUpButton alloc] initWithFrame:NSZeroRect pullsDown:NO];
    self.sourcePopup.controlSize = NSControlSizeSmall;
    self.sourcePopup.font = [NSFont systemFontOfSize:NSFont.smallSystemFontSize];
    [self bind:self.sourcePopup to:^(id sender) {
        weakSelf.selectedKey = nil;
        [weakSelf render];
    }];
    self.sourceSwitcher = [NSStackView stackViewWithViews:@[self.sourceControl, self.sourcePopup]];
    self.sourceSwitcher.orientation = NSUserInterfaceLayoutOrientationHorizontal;
    self.sourceSwitcher.spacing = 0;
    [self rebuildSourceControlSelectingProfileID:nil];
    NSMutableArray<NSString *> *ranges = [NSMutableArray array];
    for (NSNumber *days in @[@7, @30, @90]) {
        [ranges addObject:[NSString stringWithFormat:L(@"%ld Days"), (long)days.integerValue]];
    }
    self.rangeControl = [self segmentedWithLabels:ranges selected:1];
    [self bind:self.rangeControl to:^(id sender) { [weakSelf render]; }];

    NSProgressIndicator *spinner = [NSProgressIndicator new];
    spinner.style = NSProgressIndicatorStyleSpinning;
    spinner.controlSize = NSControlSizeSmall;
    spinner.displayedWhenStopped = NO;
    self.spinner = spinner;
    [self.form setAccessoryViews:@[spinner, self.sourceSwitcher, self.rangeControl]];

    NSMutableArray<NSString *> *metrics = [NSMutableArray array];
    for (UsageMetric metric = UsageMetricTotal; metric <= UsageMetricRequests; metric++) [metrics addObject:MetricTitle(metric)];
    self.metricControl = [self segmentedWithLabels:metrics selected:0];
    [self bind:self.metricControl to:^(id sender) { [weakSelf renderChart]; }];

    self.view = self.form.view;
    [NSNotificationCenter.defaultCenter addObserver:self selector:@selector(storeDidChange:)
        name:CCPetsUsageStoreDidChangeNotification object:nil];
    [self render];
    [CCPetsUsageStore loadIfStale];
    if (CCPetsUsageStore.loading) [spinner startAnimation:nil];
}

- (void)viewDidAppear {
    [super viewDidAppear];
    [self.refreshTimer invalidate];
    __weak typeof(self) weakSelf = self;
    self.refreshTimer = [NSTimer scheduledTimerWithTimeInterval:UsagePageRefreshInterval repeats:YES
        block:^(NSTimer *timer) {
        CCPetsUsagePage *page = weakSelf;
        if (!page.view.window.isVisible || page.view.window.isMiniaturized) return;
        [CCPetsUsageStore loadIfStale];
        if (CCPetsUsageStore.loading) [page.spinner startAnimation:nil];
    }];
    self.refreshTimer.tolerance = 10;
}

- (void)viewWillDisappear {
    [super viewWillDisappear];
    [self.refreshTimer invalidate];
    self.refreshTimer = nil;
}

- (void)dealloc {
    [_refreshTimer invalidate];
    [NSNotificationCenter.defaultCenter removeObserver:self];
}

- (void)storeDidChange:(NSNotification *)notification {
    [self.spinner stopAnimation:nil];
    NSString *selectedID = [self selectedAccountID];
    [self rebuildSourceControlSelectingProfileID:selectedID];
    [self computeColorSlots];
    [self render];
}

- (NSInteger)rangeDays {
    static const NSInteger ranges[] = {7, 30, 90};
    return ranges[MIN(2, MAX(0, self.rangeControl.selectedSegment))];
}

- (UsageMetric)metric {
    return (UsageMetric)MAX(0, self.metricControl.selectedSegment);
}

- (void)rebuildSourceControlSelectingProfileID:(NSString *)selectedID {
    NSMutableArray<NSDictionary *> *profiles = [NSMutableArray array];
    // 同一家账号放在一起，顺序与面板一致：Codex 在前，Claude 在后。
    [profiles addObjectsFromArray:CCPetsProfilesForProvider(CCPetsProfileProviderCodex)];
    [profiles addObjectsFromArray:CCPetsProfilesForProvider(CCPetsProfileProviderClaude)];
    self.filterProfiles = profiles;
    self.sourceControl.segmentCount = profiles.count + 1;
    [self.sourceControl setLabel:L(@"All") forSegment:0];
    [self.sourceControl setWidth:0 forSegment:0];
    [self.sourcePopup removeAllItems];
    [self.sourcePopup addItemWithTitle:L(@"All")];
    NSInteger selectedSegment = 0;
    CGFloat estimatedWidth = 44;
    for (NSUInteger index = 0; index < profiles.count; index++) {
        NSDictionary *profile = profiles[index];
        NSString *title = profile[@"displayName"] ?: profile[@"slug"] ?: profile[@"provider"];
        NSInteger segment = (NSInteger)index + 1;
        [self.sourceControl setLabel:title forSegment:segment];
        [self.sourceControl setToolTip:CCPetsTildePath(profile[@"home"]) forSegment:segment];
        [self.sourceControl setWidth:0 forSegment:segment];
        [self.sourcePopup addItemWithTitle:title];
        self.sourcePopup.lastItem.toolTip = CCPetsTildePath(profile[@"home"]);
        estimatedWidth += MAX(54, [title sizeWithAttributes:@{
            NSFontAttributeName: self.sourceControl.font
        }].width + 22);
        if (selectedID.length > 0 && [profile[@"id"] isEqualToString:selectedID]) {
            selectedSegment = segment;
        }
    }
    self.sourceControl.selectedSegment = selectedSegment;
    [self.sourcePopup selectItemAtIndex:selectedSegment];
    // 少量短名称保留快速分段切换；账号多或名称长时自动降级为下拉菜单，避免和
    // 右侧时间范围控件互相挤压。下拉菜单仍完整保留每个账号和 Home 提示。
    BOOL usePopup = profiles.count > 3 || estimatedWidth > 360;
    self.sourceControl.hidden = usePopup;
    self.sourcePopup.hidden = !usePopup;
}

- (NSDictionary *)selectedProfile {
    NSInteger selected = self.sourcePopup.hidden
        ? self.sourceControl.selectedSegment : self.sourcePopup.indexOfSelectedItem;
    NSInteger index = selected - 1;
    return index >= 0 && index < (NSInteger)self.filterProfiles.count
        ? self.filterProfiles[(NSUInteger)index] : nil;
}

- (NSString *)selectedAccountID {
    NSString *value = [self selectedProfile][@"id"];
    return [value isKindOfClass:NSString.class] && value.length > 0 ? value : nil;
}

// 色板位置：90 天、全部来源里按总用量排名，前 8 名各占一色，其余归「其他」。
// 重算时已经有颜色、仍在前 8 名的模型保留原来的位置，只有新进前 8 的模型按名次去占空出来的位置——
// 否则两个模型名次一互换，图表和图例里的颜色就跟着对调。
- (void)computeColorSlots {
    NSMutableDictionary<NSString *, NSNumber *> *totals = [NSMutableDictionary dictionary];
    for (NSString *provider in CCPetsUsageStore.results) {
        for (NSDictionary *day in CCPetsUsageStore.results[provider][@"daily"]) {
            NSDictionary *models = day[@"models"];
            for (NSString *model in models) {
                NSString *key = [NSString stringWithFormat:@"%@|%@", provider, model];
                totals[key] = @(totals[key].unsignedLongLongValue + CCPetsTotalTokens(models[model]));
            }
        }
    }
    NSArray<NSString *> *ranked = [totals keysSortedByValueUsingComparator:^NSComparisonResult(NSNumber *a, NSNumber *b) {
        return [b compare:a];
    }];
    NSUInteger colored = MIN(ranked.count, (NSUInteger)CCPetsChartColorCount);
    NSMutableDictionary<NSString *, NSNumber *> *slots = [NSMutableDictionary dictionary];
    NSMutableIndexSet *taken = [NSMutableIndexSet indexSet];
    for (NSUInteger index = 0; index < colored; index++) {
        NSInteger previous = self.colorSlots[ranked[index]] ? self.colorSlots[ranked[index]].integerValue : -1;
        if (previous < 0) continue;
        slots[ranked[index]] = @(previous);
        [taken addIndex:(NSUInteger)previous];
    }
    NSUInteger next = 0;
    for (NSUInteger index = 0; index < ranked.count; index++) {
        if (slots[ranked[index]]) continue;
        if (index >= colored) {
            slots[ranked[index]] = @(-1);
            continue;
        }
        while ([taken containsIndex:next]) next++;
        slots[ranked[index]] = @((NSInteger)next);
        [taken addIndex:next];
    }
    self.colorSlots = slots;
}

- (NSColor *)colorForKey:(NSString *)key {
    NSNumber *slot = self.colorSlots[key];
    return CCPetsChartColor(slot ? slot.integerValue : -1);
}

// 按当前来源和区间整理条目。区间合计由截取后的每日数据现加，不用数据层的 models（那是整整 90 天的）。
- (NSArray<NSDictionary *> *)entriesForRangeDays:(NSInteger)rangeDays {
    NSMutableArray<NSDictionary *> *entries = [NSMutableArray array];
    NSDictionary *selectedProfile = [self selectedProfile];
    NSString *selectedProvider = selectedProfile[@"provider"];
    NSArray<NSString *> *providers = selectedProvider.length > 0
        ? @[selectedProvider] : @[@"claude", @"codex"];
    NSArray<NSNumber *> *stamps = nil;
    for (NSString *provider in providers) {
        NSString *selectedID = selectedProfile[@"id"];
        NSDictionary *result = selectedID.length > 0
            ? CCPetsUsageStore.profileResults[selectedID] : CCPetsUsageStore.results[provider];
        NSArray<NSDictionary *> *daily = result[@"daily"];
        if (daily.count > (NSUInteger)rangeDays) {
            daily = [daily subarrayWithRange:NSMakeRange(daily.count - (NSUInteger)rangeDays, (NSUInteger)rangeDays)];
        }
        if (!stamps || daily.count > stamps.count) stamps = [daily valueForKey:@"timestamp"];
        NSMutableSet<NSString *> *models = [NSMutableSet set];
        for (NSDictionary *day in daily) [models addObjectsFromArray:[day[@"models"] allKeys]];
        for (NSString *model in models) {
            NSMutableArray<NSDictionary *> *days = [NSMutableArray arrayWithCapacity:daily.count];
            for (NSDictionary *day in daily) [days addObject:day[@"models"][model] ?: @{}];
            NSDictionary *counts = SummedCounts(days);
            if (CCPetsTotalTokens(counts) == 0 && Count(counts, @"requests") == 0) continue;
            NSMutableDictionary *entry = [@{@"key": [NSString stringWithFormat:@"%@|%@", provider, model],
                @"provider": provider, @"model": model, @"counts": counts, @"days": days} mutableCopy];
            NSString *accountName = selectedProfile[@"displayName"] ?: selectedProfile[@"slug"];
            if (accountName.length > 0) entry[@"accountName"] = accountName;
            [entries addObject:entry];
        }
    }
    self.dayStamps = stamps ?: @[];
    [entries sortUsingComparator:^NSComparisonResult(NSDictionary *a, NSDictionary *b) {
        unsigned long long left = CCPetsTotalTokens(a[@"counts"]), right = CCPetsTotalTokens(b[@"counts"]);
        return left == right ? NSOrderedSame : (left > right ? NSOrderedAscending : NSOrderedDescending);
    }];
    return entries;
}

- (void)render {
    NSInteger rangeDays = [self rangeDays];
    self.form.subtitleLabel.stringValue = [NSString stringWithFormat:L(@"Last %ld days · local usage logs"),
        (long)rangeDays];
    [self.form removeAllContent];
    self.legendItems = [NSMutableDictionary dictionary];
    self.modelRows = [NSMutableDictionary dictionary];
    if (!CCPetsUsageStore.results) {
        // 还没算完：转圈的指示器已经在说明在算，别闪一下"没有数据"。
        [self.form addFootnote:L(@"Reading local session logs…")];
        return;
    }
    if (!self.colorSlots) [self computeColorSlots];
    self.entries = [self entriesForRangeDays:rangeDays];
    if (self.selectedKey && ![[self.entries valueForKey:@"key"] containsObject:self.selectedKey]) self.selectedKey = nil;

    NSMutableDictionary *sum = SummedCounts([self.entries valueForKey:@"counts"]);
    [self.form addView:[self kpiStripWithSum:sum rangeDays:rangeDays]];
    if (Count(sum, @"background") > 0) {
        [self.form addFootnote:L(@"Background usage is included in the total. Its input, output and cache breakdown is unavailable; the corresponding metrics cover recorded details only.")];
    }
    [self.form addView:[self chartCardView]];
    if (self.entries.count > 0) [self.form addView:[self modelTable]];
    [self renderChart];
}

#pragma mark 指标条

// 五格和概览一样（同一个部件、同一套口径），只是总用量换成当前来源和区间的合计。
// 缓存写入和后台用量只在总用量标题后的 ⓘ 悬停展示，不在数字下方重复显示。
- (NSView *)kpiStripWithSum:(NSDictionary *)sum rangeDays:(NSInteger)rangeDays {
    NSString *title = [NSString stringWithFormat:L(@"Last %ld days · Total"), (long)rangeDays];
    NSMutableArray<NSArray<NSString *> *> *items = [CCPetsUsageMetricItems(title, sum, self.entries.count) mutableCopy];
    NSString *details = [NSString stringWithFormat:@"%@\n%@",
        [NSString stringWithFormat:L(@"Includes cached input %@"), CCPetsFormatTokens(Count(sum, @"cacheWrite"))],
        [NSString stringWithFormat:L(@"Background usage %@"), CCPetsFormatTokens(Count(sum, @"background"))]];
    items[0] = @[items[0][0], items[0][1], L(@"All tokens"), details];
    NSView *row = CCPetsMetricRow(items);
    CCPetsCardView *card = [CCPetsCardView new];
    row.translatesAutoresizingMaskIntoConstraints = NO;
    [card addSubview:row];
    [NSLayoutConstraint activateConstraints:@[
        [row.leadingAnchor constraintEqualToAnchor:card.leadingAnchor constant:16],
        [row.trailingAnchor constraintEqualToAnchor:card.trailingAnchor constant:-16],
        [row.topAnchor constraintEqualToAnchor:card.topAnchor constant:14],
        [row.bottomAnchor constraintEqualToAnchor:card.bottomAnchor constant:-14],
    ]];
    return card;
}

