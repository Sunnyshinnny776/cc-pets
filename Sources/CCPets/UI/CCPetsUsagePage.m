// 1234 -> 1.23K，1234567 -> 1.23M：卡片里放不下一长串数字，精确值在悬停时给。
// 先按三位有效数字舍入再定单位：999,950 直接格式化会得到 "1000K"，9,995 会得到 "10.00K"。
NSString *CCPetsFormatTokens(unsigned long long value) {
    if (value < 1000) return [NSString stringWithFormat:@"%llu", value];
    double scaled = (double)value;
    NSUInteger unit = 0;
    NSArray<NSString *> *suffixes = @[@"K", @"M", @"B", @"T"];
    while (unit < suffixes.count) {
        scaled /= 1000;
        double rounded = scaled >= 100 ? round(scaled) : (scaled >= 10 ? round(scaled * 10) / 10 : round(scaled * 100) / 100);
        if (rounded < 1000 || unit == suffixes.count - 1) {
            scaled = rounded;
            break;
        }
        unit++;
    }
    return [NSString stringWithFormat:scaled >= 100 ? @"%.0f%@" : (scaled >= 10 ? @"%.1f%@" : @"%.2f%@"),
        scaled, suffixes[unit]];
}

// 命中率 = 缓存读 / 全部输入侧（非缓存输入 + 缓存读 + 缓存写）。两家的原始口径不同，
// 但 CCPetsModelUsage 已经统一成四栏互不重叠，所以这里同一个公式。
static NSString *HitRateText(NSDictionary *counts) {
    unsigned long long side = Count(counts, @"input") + Count(counts, @"cacheRead") + Count(counts, @"cacheWrite");
    if (side == 0) return @"–";
    return [NSString stringWithFormat:@"%.0f%%", 100.0 * Count(counts, @"cacheRead") / side];
}

static NSString *ProviderTitle(NSString *provider) {
    return [provider isEqualToString:@"claude"] ? @"Claude Code" : @"Codex";
}

static NSString *EntrySourceTitle(NSDictionary *entry) {
    NSString *accountName = [entry[@"accountName"] isKindOfClass:NSString.class]
        ? entry[@"accountName"] : nil;
    return accountName.length > 0 ? accountName : ProviderTitle(entry[@"provider"]);
}

// 数据层把认不出模型的用量记在 "unknown" 名下（旧格式会话、没见过 turn_context 的续读段），
// 这个名字是内部占位，显示时换成本地化文案。
static NSString *ModelTitle(NSString *model) {
    return [model isEqualToString:@"unknown"] ? L(@"Unknown Model") : model;
}

static NSMutableDictionary *SummedCounts(NSArray<NSDictionary *> *list) {
    NSMutableDictionary *sum = [NSMutableDictionary dictionary];
    for (NSDictionary *counts in list) {
        for (NSString *key in @[@"input", @"cacheRead", @"cacheWrite", @"output", @"reasoning", @"requests", @"background"]) {
            sum[key] = @(Count(sum, key) + Count(counts, key));
        }
    }
    return sum;
}

NSDictionary *CCPetsUsageDayTotals(NSDictionary *day) {
    NSDictionary *models = [day[@"models"] isKindOfClass:NSDictionary.class] ? day[@"models"] : @{};
    return SummedCounts(models.allValues);
}

NSDictionary *CCPetsUsageSum(NSArray<NSDictionary *> *list) {
    return SummedCounts(list);
}

// 缓存写量小，不单占一格，只在总用量下面带一句。
NSArray<NSArray<NSString *> *> *CCPetsUsageMetricItems(NSString *totalTitle, NSDictionary *sum, NSUInteger modelCount) {
    unsigned long long input = Count(sum, @"input"), write = Count(sum, @"cacheWrite");
    unsigned long long output = Count(sum, @"output"), read = Count(sum, @"cacheRead");
    unsigned long long side = input + write + read;
    unsigned long long background = Count(sum, @"background");
    NSMutableArray<NSString *> *notes = [NSMutableArray array];
    if (write > 0) [notes addObject:[NSString stringWithFormat:L(@"Includes %@ cache write"), CCPetsFormatTokens(write)]];
    if (background > 0) [notes addObject:[NSString stringWithFormat:L(@"Background %@ · breakdown unavailable"), CCPetsFormatTokens(background)]];
    NSString *hit = side > 0 ? [NSString stringWithFormat:L(@"Hit rate %.0f%%"), 100.0 * read / side]
        : L(@"No cache reads yet");
    return @[
        @[totalTitle, CCPetsFormatTokens(CCPetsTotalTokens(sum)), notes.count > 0
            ? [notes componentsJoinedByString:@" · "] : L(@"All tokens")],
        @[L(@"Input"), CCPetsFormatTokens(input), L(@"Excluding cache")],
        @[L(@"Output"), CCPetsFormatTokens(output), L(@"Generated by the model")],
        @[L(@"Cached Input"), CCPetsFormatTokens(read), hit],
        @[L(@"Requests"), FormatCount(Count(sum, @"requests")), modelCount == 1 ? L(@"1 model")
            : [NSString stringWithFormat:L(@"%lu models"), (unsigned long)modelCount]],
    ];
}

